char *current_filename = NULL;

// The runtime's objects for each target, embedded in cobalt when it is built
// (Makefile: the runtime is assembled by the first-stage cobalt, then linked
// into the final one). The first stage has none: it can still produce
// assembly (-A) and objects (-c).
typedef struct {
    const uint8_t *data;
    uint64_t size;
} EmbeddedObject;
// The runtimes built in (generated C, see `cobalt embed`); the first-stage
// cobalt that assembles them (COBALT_STAGE0) has none
#ifndef COBALT_STAGE0
extern const EmbeddedObject cobalt_runtime_x86_64_linux_elf[];
extern const EmbeddedObject cobalt_runtime_x86_64_pc_windows_msvc[];
#endif

static const EmbeddedObject *embedded_runtime(const TargetInfo *target) {
#ifndef COBALT_STAGE0
    if (target->triple == TARGET_LINUX_X86_64_ELF) return cobalt_runtime_x86_64_linux_elf;
    if (target->triple == TARGET_WINDOWS_X86_64_PE) return cobalt_runtime_x86_64_pc_windows_msvc;
#endif
    (void)target;
    return NULL;
}

// cobalt embed SYMBOL object... : C source of a table of the objects
// (EmbeddedObject SYMBOL[], ending with {0, 0}) on standard output
static int embed_command(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: cobalt embed SYMBOL object...\n"); return 1; }
    printf("/* generated by cobalt embed: objects built into cobalt */\n");
    printf("#include <stdint.h>\n\ntypedef struct { const uint8_t *data; uint64_t size; } EmbeddedObject;\n\n");
    uint64_t *sizes = calloc((size_t)argc, sizeof(uint64_t));
    for (int k = 2; k < argc; k++) {
        FILE *f = fopen(argv[k], "rb");
        if (!f) { fprintf(stderr, "cobalt embed: cannot read %s\n", argv[k]); return 1; }
        printf("static const uint8_t object_%d[] = {", k - 2);
        int c;
        uint64_t n = 0;
        while ((c = fgetc(f)) != EOF) printf("%s%d,", n++ % 24 ? "" : "\n    ", c);
        printf("\n};\n");
        sizes[k] = n;
        fclose(f);
    }
    printf("\nconst EmbeddedObject %s[] = {\n", argv[1]);
    for (int k = 2; k < argc; k++) printf("    { object_%d, %llu },\n", k - 2, (unsigned long long)sizes[k]);
    printf("    { 0, 0 }\n};\n");
    free(sizes);
    return 0;
}

typedef enum { EMIT_EXECUTABLE, EMIT_OBJECT, EMIT_ASSEMBLY } EmitKind;

static uint8_t *read_binary(const char *path, size_t *size) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t *data = malloc(n > 0 ? n : 1);
    if (data && fread(data, 1, n, f) != (size_t)n) { free(data); data = NULL; }
    fclose(f);
    *size = (size_t)n;
    return data;
}

static char *read_file(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) {
        cobalt_error("Could not open input file: %s", path);
        exit(1);
    }
    fseek(f, 0, SEEK_END);
    size_t len = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *buf = malloc(len + 1);
    if (fread(buf, 1, len, f) != len) {
        cobalt_error("Failed to read file: %s", path);
        exit(1);
    }
    buf[len] = '\0';
    fclose(f);
    return buf;
}

// Only COBOL-85 is compiled in this release
static Standard parse_standard(const char *s) {
    if (!strcasecmp(s, "COBOL-85") || !strcasecmp(s, "COBOL85") || !strcmp(s, "85")) return STD_COBOL85;
    if (!strcasecmp(s, "COBOL-2002") || !strcasecmp(s, "COBOL-2014"))
        cobalt_error("%s is not supported in this release: cobalt compiles COBOL-85", s);
    else
        cobalt_error("Unknown COBOL standard '%s' (this release compiles COBOL-85)", s);
    exit(1);
}

static Strictness parse_strictness(const char *s) {
    if (!strcmp(s, "relaxed")) return STRICT_RELAXED;
    if (!strcmp(s, "normal")) return STRICT_NORMAL;
    if (!strcmp(s, "pedantic")) return STRICT_PEDANTIC;
    if (!strcmp(s, "ibm-strict")) return STRICT_IBM;
    cobalt_error("Unknown strictness level '%s' (relaxed, normal, pedantic or ibm-strict)", s);
    exit(1);
}

static void print_version(void) {
    printf("cobalt %s\n", COBALT_VERSION);
#ifdef _WIN32
    printf("Target: x86_64-pc-windows-msvc (default), x86_64-linux-elf; built %s\n", __DATE__);
#else
    printf("Target: x86_64-linux-elf (default), x86_64-pc-windows-msvc; built %s\n", __DATE__);
#endif
    printf("COBOL-85 compiler with a built-in assembler and linker. MIT license.\n");
}

